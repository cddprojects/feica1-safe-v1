<div class="page-head"><div class="wrap"><span class="eyebrow">Work types</span><h1>How remote, online and flexible work differ</h1></div></div>
<section><div class="wrap article">
<p class="byline">Role Glide &middot; Last reviewed October 2026</p>
<p class="lede">Remote, online and flexible often appear together in job postings, but each describes a different part of the arrangement.</p>

<div class="takeaways"><h2>The short version</h2><ul>
<li>Remote describes where the work is done.</li>
<li>Online describes how the work is completed or delivered.</li>
<li>Flexible describes the hours or workload.</li>
<li>A job can include one, two or all three arrangements.</li>
</ul></div>
<h2>Work location</h2>
<p>Remote work is performed away from the employer’s usual workplace. Hybrid combines on-site and remote days; a posting that requires regular office attendance is hybrid rather than fully remote. The guide <a href="/remote-work-canada/">Remote work in Canada</a> provides more detail.</p>
<h2>How the work is delivered</h2>
<p>Online work is done or delivered over the internet, either from home or at the employer’s workplace. A posting that lists only “online job” may still require a specific workplace or province. The guide <a href="/online-work-canada/">Online work in Canada</a> provides more detail.</p>
<h2>Hours</h2>
<p>Flexible work may provide some choice over schedule or workload. In the Labour Force Survey, part-time work is usually fewer than 30 hours per week at a person’s main job. Flexible scheduling can apply to full-time or part-time employment; part-time refers to hours rather than a pay type or independent contract work. The <a href="/flexible-work-canada/">flexible-work guide</a> provides more detail.</p>
<h2>Why the difference matters</h2>
<p>For work alongside a main job, hours may be the main concern. For less commuting, location matters. For a particular kind of work, the duties matter most. If a posting uses these terms without defining them, the location, duties and hours need a closer look. Related guides cover <a href="/article-read-a-remote-ad/">job postings</a> and <a href="/article-second-path/">second jobs</a>.</p>

