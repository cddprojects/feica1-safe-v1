<div class="page-head"><div class="wrap"><span class="eyebrow">Work types</span><h1>Remote, online and flexible work.</h1><p class="lede">An overview of common work arrangements in Canada, including where the work takes place, how it is delivered and how hours are scheduled.</p></div></div>
<section><div class="wrap">
<div class="types">
<article class="type"><div><span class="n">01 · Location</span><h3><a href="/remote-work-canada/">Remote</a></h3></div><div><p>Remote jobs are completed away from the employer’s workplace. Some allow work from anywhere in Canada, while others are limited to a province. Hybrid jobs include on-site days. Work-location filters help separate these arrangements.</p><p><a href="/remote-work-canada/">Read the guide</a></p></div></article>
<article class="type"><div><span class="n">02 · How work is done</span><h3><a href="/online-work-canada/">Online</a></h3></div><div><p>Online work is completed or delivered over the internet, including customer support, writing, design, bookkeeping, tutoring, moderation and software development. It may be done at home or at an employer’s workplace.</p><p><a href="/online-work-canada/">Read the guide</a></p></div></article>
<article class="type"><div><span class="n">03 · Hours</span><h3><a href="/flexible-work-canada/">Flexible</a></h3></div><div><p>This category includes flexible hours, deadline-based projects and part-time work. Statistics Canada generally defines part-time work as fewer than 30 hours a week. Income and hours depend on the agreement or contract.</p><p><a href="/flexible-work-canada/">Read the guide</a></p></div></article>
</div>
<p class="src-note">For current openings, a work-location filter is more precise than a keyword search for “work from home.”</p>
</div></section>

