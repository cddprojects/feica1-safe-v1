<div class="head page-intro reveal"><span class="eyebrow">Everyone has a reason</span><h1>Why people take on more work.</h1><p class="lede">In August 2023, Statistics Canada asked people with more than one job for their main reason. Income was the main reason for many respondents, but not for everyone.</p></div>
<div class="tiles">
<article class="tile reveal"><h3>Help with everyday costs</h3><p>Paying for essentials like groceries or housing was the top reason.</p></article>
<article class="tile reveal"><h3>Add income</h3><p>Nearly as many wanted money beyond what their main job pays.</p></article>
<article class="tile reveal"><h3>Build experience</h3><p>Some wanted to do work they care about, and a second job can help develop experience in a new field.</p></article>
<article class="tile reveal"><h3>Find hours that fit</h3><p>Part-time or flexible work can fit around a main job, school, family or health needs.</p></article>
</div>
<p class="src-note">Source: Statistics Canada, August 2023, people aged 15 to 69 who already had more than one job. These results describe current multiple jobholders rather than the outcome of a new job search. <a href="/article-second-path/">See the full numbers</a>.</p>
</div></section>
<section class="alt"><div class="wrap split">
<div><span class="eyebrow">What changes with each type</span><h2>Where, how and when you work.</h2>
<p><b>Remote work</b> can reduce or remove the commute, though some positions still require residence in a particular province or availability in a particular time zone.</p>
<p><b>Online work</b> is completed or delivered over the internet, but it is not necessarily remote or flexible.</p>
<p><b>Flexible work</b> can mean a shorter week or more control over working hours. The employer or client, expected workload, schedule and method of payment determine how flexible the arrangement is in practice.</p>
<p><a href="/work-types/">See how the three differ &rarr;</a></p></div>
<div><span class="eyebrow">Information sources</span><h2>Canadian information for informed decisions.</h2>
<p>Work arrangements are described across job postings, labour-market reports, tax guidance and provincial or territorial employment resources.</p>
<p>The guides organize this information around common search questions: where work takes place, how hours are set, how pay is described and whether a role is employment or independent contract work.</p>
<p>Source links are included where figures or official rules are discussed.</p></div>
